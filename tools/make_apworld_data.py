#!/usr/bin/env python3
"""Generate apworld/gizmos_and_gadgets/data.py from the extracted tables in data/.

Usage: python tools/make_apworld_data.py
Inputs: data/parts_all.tsv, data/race_requirements.tsv, data/flight_requirements.tsv, data/warehouse_counts.tsv
"""
import csv
import os

ROOT = os.path.join(os.path.dirname(__file__), '..')
D = lambda n: os.path.join(ROOT, 'data', n)


def rows(name):
    with open(D(name), newline='') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def main():
    parts = {}
    for r in rows('parts_all.tsv'):
        parts.setdefault(int(r['vehicle']), []).append(
            (int(r['id']), int(r['group'], 16), int(r['tier']), int(r['cosmetic']), r['name']))
    req = {}
    for name in ('race_requirements.tsv', 'flight_requirements.tsv'):
        for r in rows(name):
            stat = [int(x.split(':')[0], 16) for x in r['min_tier_per_slot_others_max'].split(',')]
            req[int(r['vehicle'])] = (int(r['all_slots_tier_ge']), stat)
    doors = {int(r['vehicle']): int(r['puzzle_doors']) for r in rows('warehouse_counts.tsv')}
    out = ['# Generated by tools/make_apworld_data.py from data/*.tsv -- do not edit.',
           '# PARTS[v] = [(part id, group, tier, cosmetic, name)], v = building * 5 + level (0-based).',
           '# RACE[v] = (k, stat groups): a build wins if every stat group has a part of tier >= min(k, max tier).',
           '# DOORS[v] = number of puzzle doors.', '',
           'BUILDINGS = ("Automotive", "Aircraft", "Alternative Energy")', '', 'PARTS = {']
    for v in range(15):
        out.append(f'    {v}: [')
        for p in sorted(parts[v]):
            out.append(f'        {p!r},')
        out.append('    ],')
    out += ['}', '', 'RACE = {']
    for v in range(15):
        out.append(f'    {v}: ({req[v][0]}, {tuple(req[v][1])!r}),')
    out += ['}', '', f'DOORS = {doors!r}', '']
    dst = os.path.join(ROOT, 'apworld', 'gizmos_and_gadgets', 'data.py')
    open(dst, 'w').write('\n'.join(out))
    print('wrote', dst, sum(len(p) for p in parts.values()), 'parts')


if __name__ == '__main__':
    main()
